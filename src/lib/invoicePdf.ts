import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { PDFFont } from "pdf-lib";
import { computeInvoiceTotal, formatMoney } from "./invoices";
import type { Client, Invoice } from "./types";

/** Word-wrap a line to fit `maxWidth` at the given font/size. */
function wrapText(
  text: string,
  font: PDFFont,
  size: number,
  maxWidth: number,
): string[] {
  const words = text.split(/\s+/).filter((w) => w.length > 0);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (font.widthOfTextAtSize(next, size) <= maxWidth) {
      line = next;
    } else {
      if (line) lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines.length > 0 ? lines : [""];
}

/**
 * Build a one-page PDF for a single invoice. Pure function: no database,
 * no session, no network — the API route owns auth and ownership checks.
 * Uses only the built-in Helvetica font, so there is nothing to embed.
 */
export async function buildInvoicePdf(
  invoice: Invoice,
  client: Client | undefined,
  statusLabel: string,
): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Invoice — ${invoice.description}`);
  doc.setSubject(`Invoice ${invoice.id}`);
  const page = doc.addPage([595.28, 841.89]); // A4
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const black = rgb(0.07, 0.11, 0.16);
  const grey = rgb(0.39, 0.45, 0.55);
  const margin = 56;
  const maxWidth = page.getWidth() - margin * 2;
  let y = page.getHeight() - margin;

  const draw = (
    text: string,
    size: number,
    useBold = false,
    color = black,
  ) => {
    const lines = wrapText(text, useBold ? bold : font, size, maxWidth);
    for (const line of lines) {
      page.drawText(line, {
        color,
        font: useBold ? bold : font,
        size,
        x: margin,
        y,
      });
      y -= size + 8;
    }
  };

  draw("Invoice", 24, true);
  y -= 12;
  draw(`Client: ${client?.name ?? "Unknown client"}${client?.company ? ` — ${client.company}` : ""}`, 12);
  if (client?.email) draw(`Email: ${client.email}`, 12, false, grey);
  y -= 8;
  draw(`Description: ${invoice.description}`, 12);
  draw(`Amount: ${formatMoney(invoice.amount)}`, 12);
  if (invoice.discountRate > 0) draw(`Discount: ${invoice.discountRate}%`, 12);
  if (invoice.taxRate > 0) draw(`Tax: ${invoice.taxRate}% (on the discounted amount)`, 12);
  draw(`Total due: ${formatMoney(computeInvoiceTotal(invoice))}`, 12, true);
  draw(`Status: ${statusLabel}`, 12);
  draw(`Issued: ${invoice.issuedDate}`, 12);
  draw(`Due: ${invoice.dueDate}`, 12);
  y -= 8;
  draw("Generated by ClientDesk.", 10, false, grey);

  return doc.save();
}
